import { chromium } from '@playwright/test';
import fs from 'node:fs';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const dir=fileURLToPath(new URL('.',import.meta.url));
const browser=await chromium.launch({channel:'chrome',headless:true});
const results={checkedAt:new Date().toISOString(),scope:'Static design prototype only; localhost Chrome. Not platform production acceptance.',checks:[],errors:[]};
try{
 for(const width of [1440,768,375]){
  const page=await browser.newPage({viewport:{width,height:1000}});
  page.on('pageerror',e=>results.errors.push(e.message));
  await page.goto('http://127.0.0.1:3011/prototype.html');
  assert.equal(await page.locator('#home').isVisible(),true);
  assert.equal(await page.locator('.entrygrid button').count(),6);
  await page.getByLabel('搜索知识或描述目标').fill('token 是什么');
  await page.getByRole('button',{name:'查找内容',exact:true}).click();
  assert.equal(await page.locator('#learn').isVisible(),true);
  await page.locator('.nav [data-pane=updates]').click();
  assert.equal(await page.locator('#updates').isVisible(),true);
  await page.locator('.nav [data-pane=home]').click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:dir+`prototype-${width}.png`,fullPage:true});
  await page.locator('#home [data-scene=three]').click();
  assert.match(await page.locator('#sceneTitle').innerText(),/资产/);
  await page.locator('#openroute').click();
  assert.match(await page.locator('#flowtitle').innerText(),/单张图片/);
  await page.locator('#steps input').first().check();
  assert.equal(await page.locator('#progresslabel').innerText(),'1/5');
  await page.locator('#workflow [data-scene=video]').click();
  assert.equal(await page.locator('#progresslabel').innerText(),'0/5');
  await page.locator('#workflow [data-scene=three]').click();
  assert.equal(await page.locator('#progresslabel').innerText(),'1/5');
  await page.locator('.nav [data-pane=tools]').click();
  await page.getByLabel('搜索工具').fill('Meshy');
  assert.equal(await page.locator('.toolcard').count(),1);
  await page.getByRole('button',{name:'加入对照 Meshy',exact:true}).click();
  await page.getByLabel('搜索工具').fill('Tripo');
  await page.getByRole('button',{name:'加入对照 Tripo',exact:true}).click();
  assert.equal(await page.locator('#comparegrid article').count(),2);
  await page.getByLabel('搜索工具').fill('not-a-tool');
  assert.match(await page.locator('#toolgrid').innerText(),/没有匹配/);
  await page.locator('.nav [data-pane=budget]').click();
  assert.equal(await page.locator('#budgetmoney').innerText(),'¥18.00');
  await page.locator('#attempts').fill('2');
  assert.equal(await page.locator('#budgetmoney').innerText(),'¥12.00');
  await page.locator('#attempts').fill('0');
  assert.equal(await page.locator('#budgetmoney').innerText(),'请检查输入');
  await page.locator('.nav [data-pane=home]').click();
  await page.getByLabel('搜索知识或描述目标').fill('我想做一段视频');
  await page.getByRole('button',{name:'查找内容'}).click();
  assert.match(await page.locator('#flowtitle').innerText(),/30 秒/);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  results.checks.push({width,passed:['unified six sections','knowledge search','updates section','home layout','scene switching','workflow progress isolation','tool search','candidate comparison','empty search','budget arithmetic','invalid budget','goal keyword routing'],pageOverflow:false});
  await page.close();
 }
 assert.equal(results.errors.length,0);
 fs.writeFileSync(dir+'prototype-verification.json',JSON.stringify(results,null,2));
 console.log(JSON.stringify(results,null,2));
}finally{await browser.close();}
